USE EduMonitorAnalysis;
GO

IF COL_LENGTH(N'dbo.ACADEMIC_RECOMMENDATION', N'id_estudiante') IS NULL
    ALTER TABLE dbo.ACADEMIC_RECOMMENDATION
        ADD id_estudiante INT NULL;
GO

IF COL_LENGTH(N'dbo.ACADEMIC_RECOMMENDATION', N'estudiante') IS NULL
    ALTER TABLE dbo.ACADEMIC_RECOMMENDATION
        ADD estudiante NVARCHAR(200) NULL;
GO

IF COL_LENGTH(N'dbo.ACADEMIC_RECOMMENDATION', N'fecha_evidencia_utc') IS NULL
    ALTER TABLE dbo.ACADEMIC_RECOMMENDATION
        ADD fecha_evidencia_utc DATETIME2 NULL;
GO

IF EXISTS (
    SELECT 1
    FROM sys.indexes
    WHERE name = N'UQ_ACADEMIC_RECOMMENDATION_EVENT_ACTIVITY'
      AND object_id = OBJECT_ID(N'dbo.ACADEMIC_RECOMMENDATION')
      AND filter_definition IS NULL
)
    DROP INDEX UQ_ACADEMIC_RECOMMENDATION_EVENT_ACTIVITY
        ON dbo.ACADEMIC_RECOMMENDATION;
GO

IF NOT EXISTS (
    SELECT 1 FROM sys.indexes
    WHERE name = N'UQ_ACADEMIC_RECOMMENDATION_EVENT_ACTIVITY'
      AND object_id = OBJECT_ID(N'dbo.ACADEMIC_RECOMMENDATION')
)
    CREATE UNIQUE INDEX UQ_ACADEMIC_RECOMMENDATION_EVENT_ACTIVITY
        ON dbo.ACADEMIC_RECOMMENDATION(source_event_id, id_actividad_moodle)
        WHERE id_estudiante IS NULL;
GO

IF NOT EXISTS (
    SELECT 1 FROM sys.indexes
    WHERE name = N'UQ_ACADEMIC_RECOMMENDATION_EVENT_ACTIVITY_STUDENT'
      AND object_id = OBJECT_ID(N'dbo.ACADEMIC_RECOMMENDATION')
)
    CREATE UNIQUE INDEX UQ_ACADEMIC_RECOMMENDATION_EVENT_ACTIVITY_STUDENT
        ON dbo.ACADEMIC_RECOMMENDATION(source_event_id, id_actividad_moodle, id_estudiante)
        WHERE id_estudiante IS NOT NULL;
GO
